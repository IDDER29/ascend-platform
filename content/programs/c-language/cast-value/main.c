#include <stdio.h>

int main(void) {
    printf("(int)3.99   = %d\n", (int) 3.99);
    printf("(int)-3.99  = %d\n", (int) -3.99);
    printf("(unsigned char)300 = %d\n", (unsigned char) 300);
    printf("(double)7 / 2  = %.1f\n", (double) 7 / 2);
    printf("(double)(7 / 2) = %.1f\n", (double) (7 / 2));
    return 0;
}
